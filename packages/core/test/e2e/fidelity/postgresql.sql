-- One table feature per object. The fidelity test rebuilds this schema from the generated Drizzle schema.

-- Primary key with its own name.
CREATE TABLE authors (
  id serial,
  email varchar(100) NOT NULL,
  handle text,
  CONSTRAINT authors_pk PRIMARY KEY (id),
  CONSTRAINT authors_email_key UNIQUE (email),
  CONSTRAINT authors_handle_key UNIQUE NULLS NOT DISTINCT (handle)
);

-- Foreign keys with actions, a composite unique constraint as a foreign key target.
CREATE TABLE posts (
  id serial PRIMARY KEY,
  author_id integer NOT NULL,
  editor_id integer,
  slug text NOT NULL,
  CONSTRAINT posts_author_fk FOREIGN KEY (author_id) REFERENCES authors (id) ON DELETE CASCADE ON UPDATE RESTRICT,
  CONSTRAINT posts_editor_fk FOREIGN KEY (editor_id) REFERENCES authors (id) ON DELETE SET NULL,
  CONSTRAINT posts_author_slug_key UNIQUE (author_id, slug)
);

-- Composite foreign key.
CREATE TABLE editions (
  id serial PRIMARY KEY,
  post_author integer NOT NULL,
  post_slug text NOT NULL,
  CONSTRAINT editions_post_fk FOREIGN KEY (post_author, post_slug) REFERENCES posts (author_id, slug)
);

-- Composite primary key.
CREATE TABLE post_tags (
  post_id integer NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  name text NOT NULL,
  PRIMARY KEY (post_id, name)
);

-- Foreign key to its own table.
CREATE TABLE nodes (
  id serial PRIMARY KEY,
  parent_id integer,
  CONSTRAINT nodes_parent_fk FOREIGN KEY (parent_id) REFERENCES nodes (id) ON DELETE SET DEFAULT
);

-- No keys at all.
CREATE TABLE audit_log (
  message text NOT NULL,
  at timestamptz NOT NULL DEFAULT now()
);

-- CHECK constraints: one column, two columns, a list of values.
CREATE TABLE prices (
  id serial PRIMARY KEY,
  amount numeric(10,2) NOT NULL,
  discount numeric(10,2),
  currency text NOT NULL,
  CONSTRAINT prices_amount_positive CHECK (amount > 0),
  CONSTRAINT prices_discount_below_amount CHECK (discount IS NULL OR discount < amount),
  CONSTRAINT prices_currency_known CHECK (currency = ANY (ARRAY['EUR', 'USD', 'it''s']))
);

-- Indexes: one feature per index.
CREATE TABLE documents (
  id serial PRIMARY KEY,
  owner_id integer NOT NULL,
  title text NOT NULL,
  body jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE INDEX documents_owner_idx ON documents (owner_id);
CREATE INDEX documents_owner_created_idx ON documents (owner_id, created_at DESC NULLS LAST) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX documents_title_lower_key ON documents (lower(title)) WHERE deleted_at IS NULL;
CREATE INDEX documents_body_gin ON documents USING gin (body jsonb_path_ops);
CREATE INDEX documents_body_section_idx ON documents ((body ->> 'section'));
CREATE INDEX documents_title_pattern_idx ON documents (title text_pattern_ops);
CREATE INDEX documents_created_brin ON documents USING brin (created_at) WITH (pages_per_range = 32);
CREATE INDEX documents_title_c_idx ON documents (title COLLATE "C");
CREATE INDEX documents_deleted_nulls_first_idx ON documents (deleted_at NULLS FIRST);
CREATE INDEX documents_title_hash ON documents USING hash (title);

-- Columns: identity, generated, collation, and types without a Drizzle builder.
CREATE TABLE kinds (
  id integer GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 5) PRIMARY KEY,
  ref bigint GENERATED BY DEFAULT AS IDENTITY,
  down smallint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY -1),
  small smallserial,
  title text NOT NULL,
  title_upper text GENERATED ALWAYS AS (upper(title)) STORED,
  title_c text COLLATE "C",
  payload bytea,
  search tsvector,
  address inet,
  span interval,
  spot point,
  flags bit(3),
  grid integer[][],
  label character(2),
  price money,
  doc xml
);

-- An enum that no column uses, a sequence that no column owns, and a column that takes its default from it.
CREATE TYPE mood AS ENUM ('sad', 'ok', 'it''s');
CREATE SEQUENCE invoice_number AS bigint START WITH 1000 INCREMENT BY 10 MINVALUE 1000 MAXVALUE 99999999 CACHE 5 CYCLE;
CREATE TABLE invoices (
  id serial PRIMARY KEY,
  number bigint NOT NULL DEFAULT nextval('invoice_number')
);
